import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

export async function verifyDrawing({ cdp, evaluate, click, until, delay, elements }) {
  const strokes = () => elements.filter(item => item.element_type.startsWith('drawing:'))
  await click('[aria-label="Desenhar"]')
  assert.equal(await evaluate('document.querySelectorAll(".drawing-instruments svg").length'), 6)
  await click('[aria-label="Fixar painel"]')
  for (let i = 1; i <= 6; i++) {
    await click(`.drawing-instruments button:nth-child(${i})`)
    assert.equal(await evaluate(`document.querySelector('.drawing-instruments button:nth-child(${i})').getAttribute('aria-pressed')`), 'true')
  }
  await click('.drawing-instruments button:nth-child(2)')
  await click('.drawing-widths [aria-label="5px"]')
  await click('.drawing-levels [aria-label="Forte"]')
  await evaluate(`(() => { const input=document.querySelector('[aria-label="Cor personalizada"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'#ab3456');input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true})); })()`)
  const draw = async (points, hold = false) => {
    const rect = await evaluate(`(() => { const r=document.querySelector('.drawing-input-layer').getBoundingClientRect();return {x:r.x,y:r.y} })()`)
    const coords = points.map(([x, y]) => ({ x: rect.x + x, y: rect.y + y }))
    await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...coords[0], button: 'left', clickCount: 1 })
    for (const p of coords.slice(1)) await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', ...p, button: 'left', buttons: 1 })
    if (hold) await delay(800)
    await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', ...coords.at(-1), button: 'left', clickCount: 1 })
  }
  await draw([[120, 160], [145, 170], [170, 160], [200, 170]], true)
  await until(() => strokes().length === 1, 'Drawing did not save')
  assert.equal(strokes()[0].data.width, 5)
  assert.equal(strokes()[0].data.color, '#ab3456')
  assert(strokes()[0].data.points.at(-1).x < 200, 'Strong smoothing did not affect points')
  assert(strokes()[0].data.points.length > 2, 'Disabled shape adjustment changed the stroke')
  assert(await evaluate('!!document.querySelector(".drawing-panel")'), 'Pinned panel closed')
  const first = structuredClone(strokes()[0])
  await click('.drawing-swatches button:first-child')
  assert.deepEqual(strokes()[0], first, 'Changing active color modified an old drawing')
  await click('.drawing-hold input')
  await draw([[110, 240], [140, 241], [170, 239], [210, 240]], true)
  await until(() => strokes().length === 2, 'Held shape did not save')
  assert.equal(strokes()[1].data.points.length, 2, 'Hold did not adjust the line')
  await click('.drawing-panel .tool-inline-actions button:first-child')
  await until(() => strokes().length === 1, 'Existing last-stroke undo did not remove the held shape')
  assert.deepEqual(strokes()[0], first)
  await draw([[110, 240], [140, 241], [170, 239], [210, 240]], true)
  await until(() => strokes().length === 2, 'Redrawing after last-stroke undo did not save')
  await mkdir('test-results', { recursive: true })
  await writeFile('test-results/drawing-panel.png', Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await cdp('Page.reload')
  await until(() => evaluate('document.querySelectorAll(".drawing-layer .drawing-stroke").length === 2'), 'Drawings missing after reload')
  assert.deepEqual(strokes()[0], first)
  await click('[aria-label="Desenhar"]')
  await click('[aria-label="Fixar painel"]')
  await click('.drawing-instruments button:last-child')
  await draw([[120, 160], [130, 165]])
  await until(() => strokes().length === 1, 'Existing eraser did not remove the touched stroke')
  await click('[aria-label="Desafixar painel"]')
  await draw([[320, 360], [330, 365]])
  assert.equal(await evaluate('!!document.querySelector(".drawing-panel")'), false, 'Unpinned panel did not close on outside click')
  await click('[aria-label="Desenhar"]')
  await click('.drawing-instruments button:nth-child(2)')
  await evaluate('document.querySelector(".drawing-levels button").focus()')
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter' })
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter' })
  assert.equal(await evaluate('document.querySelector(".drawing-levels button").getAttribute("aria-pressed")'), 'true')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false })
  await delay(200)
  assert(await evaluate(`(() => { const r=document.querySelector('.drawing-tool-drawer').getBoundingClientRect(); const c=document.querySelector('.drawing-tool-drawer .tool-drawer-content'); return r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight && c.scrollHeight>c.clientHeight })()`), 'Mobile panel does not fit or scroll')
  console.log('PASS: drawing tools, thickness, real smoothing, held line, custom color, old stroke preservation, save/reload, eraser, pin, keyboard and mobile panel')
}
